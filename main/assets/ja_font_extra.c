extern const lv_font_t lv_font_simsun_16_cjk;
extern const lv_font_t lv_font_montserrat_16;

static const JaExtraGlyph *ja_extra_find(uint32_t codepoint)
{
    for (size_t i = 0; i < sizeof(kJaExtraGlyphs) / sizeof(kJaExtraGlyphs[0]); ++i) {
        if (kJaExtraGlyphs[i].codepoint == codepoint) {
            return &kJaExtraGlyphs[i];
        }
    }
    return NULL;
}

static bool ja_extra_get_glyph_dsc(const lv_font_t *font,
                                   lv_font_glyph_dsc_t *dsc,
                                   uint32_t letter,
                                   uint32_t letter_next)
{
    (void)letter_next;
    const JaExtraGlyph *glyph = ja_extra_find(letter);
    if (!font || !dsc) return false;
    if (!glyph) {
        if (!lv_font_simsun_16_cjk.get_glyph_dsc(&lv_font_simsun_16_cjk,
                                                 dsc,
                                                 letter,
                                                 letter_next)) {
            if (!lv_font_montserrat_16.get_glyph_dsc(&lv_font_montserrat_16,
                                                     dsc,
                                                     letter,
                                                     letter_next)) {
                return false;
            }
        }
        // Keep the composite font as the resolved owner. Some LVGL draw
        // backends ask the root font for the bitmap instead of following the
        // resolved fallback font.
        dsc->resolved_font = font;
        return true;
    }
    dsc->resolved_font = font;
    dsc->adv_w = glyph->adv_w;
    dsc->box_w = glyph->box_w;
    dsc->box_h = glyph->box_h;
    dsc->ofs_x = glyph->ofs_x;
    dsc->ofs_y = glyph->ofs_y;
    dsc->bpp = 1;
    dsc->is_placeholder = 0;
    return true;
}

static const uint8_t *ja_extra_get_glyph_bitmap(const lv_font_t *font,
                                                 uint32_t letter)
{
    (void)font;
    const JaExtraGlyph *glyph = ja_extra_find(letter);
    if (glyph) return &kJaExtraGlyphBitmap[glyph->bitmap_offset];
    const uint8_t *bitmap = lv_font_simsun_16_cjk.get_glyph_bitmap(
        &lv_font_simsun_16_cjk, letter);
    return bitmap ? bitmap : lv_font_montserrat_16.get_glyph_bitmap(
                           &lv_font_montserrat_16, letter);
}

